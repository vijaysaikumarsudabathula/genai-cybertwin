# -*- coding: utf-8 -*-
import docx
import pandas as pd
from build_helpers import (CT_ROOT, add_heading2, add_body, add_caption, add_table_title,
                             add_ieee_table, OUT)

doc = docx.Document(str(OUT))

gt = pd.read_csv(CT_ROOT / "results" / "genai_grounding_tests.csv")
n_pass = gt["passed"].astype(str).isin(["True", "true", "1"]).sum()

add_heading2(doc, "H. GenAI Narration Grounding Evaluation (RQ5)")
add_body(doc,
    f"Seven narratives were generated by the GenAI narration layer for a curated set of events "
    "chosen to exercise specific evidence conditions: a confident correct prediction for each of the "
    "three classes, a high-confidence misclassification, a near-50/50 low-confidence prediction, and "
    "counterfactual results ranging from a large probability reduction to a negligible one. Table V "
    f"summarizes six manual grounding tests constructed around these narratives; all {n_pass} of "
    f"{len(gt)} passed on inspection.")

rows = []
label_map = {
    "missing_counterfactual_field": "Missing counterfactual data",
    "low_confidence_event": "Low-confidence (~50/50) event",
    "no_counterfactual_but_recommendation_requested": "Recommendation with no per-event counterfactual",
    "dominant_feature_outside_actionable_set": "Dominant feature not actionable",
    "misclassification_should_not_imply_true_label_is_wrong": "Misclassification framing",
    "no_ioc_fabrication": "No fabricated indicators (IPs/CVEs/malware names)",
}
for _, r in gt.iterrows():
    passed = "Pass" if str(r["passed"]) in ("True", "true", "1") else "Fail"
    rows.append([label_map.get(r["scenario"], r["scenario"]), passed])

add_table_title(doc, "TABLE V. GENAI GROUNDING TEST RESULTS")
add_ieee_table(doc, headers=["Grounding scenario tested", "Result"], rows=rows,
               col_widths_in=[2.2, 0.5], font_pt=7.2)
add_caption(doc, "TABLE V. Manual, self-assessed grounding checks against the narration layer's "
                 "own generated text \u2014 not an automated benchmark scoring an external LLM API; "
                 "stated explicitly rather than presented as a fully automated evaluation harness.")

add_body(doc,
    "The most informative of these tests is the dominant-feature case: for an event whose "
    "classification was driven primarily by a feature outside the actionable set the counterfactual "
    "engine is permitted to modify, the narration layer reported that available interventions had "
    "negligible effect rather than fabricating an effective one \u2014 the correct behavior when the "
    "true driver of a decision cannot be acted upon by any modeled control. In answer to RQ5, "
    "restricting a generative-AI narration layer to structured, pre-computed evidence and an explicit "
    "instruction to report missing or out-of-scope information as such, rather than infer it, "
    "produces narratives that pass every constructed adversarial-evidence check in this evaluation.")

doc.save(str(OUT))
print("Section V part 3 (H) done.")
